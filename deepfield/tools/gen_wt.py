# SCAN's wavetables, from Pocket Poly's spectra (app/engine/wt.c): three tables (ANALOG, VOX, GLASS) of 16 frames,
# each 128 samples, in five band-limited copies (64, 32, 16, 8 and 4 harmonics), as int16 in flash. Every frame is
# normalised to the same peak (its full copy's), so a sweep through SHAPE keeps its level, and so does a note crossing
# from one copy to the next; and a gain for each frame at five settings of MASS (DF_WT_GAIN[frame][5]) that brings it
# to the same loudness (RMS) through SCAN's MASS low-pass (one pole at 3 to 192 times the note: drone.c), as a
# peak-normalised cluster is far quieter than a sine, and darker quieter still: MASS changes the colour, not the
# level, as on SOLAR. Written as the C header drone.c includes. Deterministic.
# Run by the build (fm1.toml gen) from deepfield/: python3 tools/gen_wt.py build/gen/df_wt.h
import math, pathlib, sys

TABLES, FRAMES, LEN, MIPS, NH = 3, 16, 128, 5, 64
MIP_MAX = [64, 32, 16, 8, 4]

def gauss(x, w):
    return math.exp(-(x * x) / (2.0 * w * w))

def spectrum(table, frame):
    t = frame / (FRAMES - 1)
    spec = [0.0] * (NH + 1)
    seg = t * 4.0
    s, f = int(seg), seg - math.floor(seg)
    if seg >= 4.0:                       # the last frame is the last keyframe itself
        s, f = 3, 1.0
    if table == 0:                       # ANALOG: sine, triangle, saw, square, a narrowing pulse
        for k in range(1, NH + 1):
            h = float(k)
            a = [1.0 if k == 1 else 0.0,
                 ((-1.0 if k & 2 else 1.0) / (h * h)) if k & 1 else 0.0,
                 1.0 / h,
                 (1.0 / h) if k & 1 else 0.0,
                 math.sin(math.pi * h * 0.12) / h]
            spec[k] = a[s] * (1.0 - f) + a[s + 1] * f
    elif table == 1:                     # VOX: two formants through A E I O U, in harmonics of a 150 Hz voice
        F1, F2 = [5.3, 3.5, 1.9, 3.0, 2.1], [8.0, 13.0, 15.0, 5.6, 4.0]
        f1 = F1[s] * (1.0 - f) + F1[s + 1] * f
        f2 = F2[s] * (1.0 - f) + F2[s + 1] * f
        for k in range(1, 41):
            h = float(k)
            spec[k] = (gauss(h - f1, 1.2) + 0.6 * gauss(h - f2, 1.8) + 0.08 / h) / (0.6 + 0.1 * h)
    else:                                # GLASS: a few low partials, then a cluster that climbs and thins
        c, w = 6.0 + t * 34.0, 1.5 + t * 2.5
        spec[1], spec[2], spec[3], spec[5] = 1.0, 0.35 * (1.0 - t), 0.25, 0.18 * t
        for k in range(4, NH + 1):
            h = float(k)
            spec[k] += 0.9 * gauss(h - c, w) * (1.0 if k & 1 else 0.55) + 0.5 * gauss(h - 2.0 * c, w * 1.5)
    return spec

def build():
    sin128 = [math.sin(2.0 * math.pi * i / LEN) for i in range(LEN)]
    out = [[[None] * FRAMES for _ in range(MIPS)] for _ in range(TABLES)]
    gain = []
    for table in range(TABLES):
        for frame in range(FRAMES):
            spec, g = spectrum(table, frame), 1.0
            for mip in range(MIPS):
                wave = [0.0] * LEN
                for k in range(1, min(MIP_MAX[mip], NH) + 1):
                    a = spec[k]
                    if a:
                        for i in range(LEN):
                            wave[i] += a * sin128[(i * k) % LEN]
                if mip == 0:
                    g = 30000.0 / max(1e-6, max(abs(x) for x in wave))
                out[table][mip][frame] = [max(-32767, min(32767, int(round(x * g)))) for x in wave]
            for m in range(5):            # through the low-pass at MASS m / 4: |H(h)|^2 = 1 / (1 + (h / r)^2)
                r = 3.0 * 2.0 ** (6.0 * m / 4.0)
                pw = sum((spec[k] * g) ** 2 * 0.5 / (1.0 + (k / r) ** 2) for k in range(1, NH + 1))
                gain.append(min(6.0, 12000.0 / max(1.0, math.sqrt(pw))))   # at most 15.6 dB up
    return out, gain

def main():
    dst = pathlib.Path(sys.argv[1])
    t, gain = build()
    rows = []
    for table in range(TABLES):
        for mip in range(MIPS):
            for frame in range(FRAMES):
                rows.append("    " + ", ".join(str(v) for v in t[table][mip][frame]) + ",")
    dst.parent.mkdir(parents=True, exist_ok=True)
    dst.write_text("/* generated by deepfield/tools/gen_wt.py: SCAN's wavetables, [table][mip][frame][sample] */\n"
                   "#pragma once\n#include <stdint.h>\n"
                   f"#define DF_WT_TABLES {TABLES}u\n#define DF_WT_MIPS {MIPS}u\n#define DF_WT_FRAMES {FRAMES}u\n"
                   f"#define DF_WT_LEN {LEN}u\n"
                   f"static const int16_t DF_WT[{TABLES * MIPS * FRAMES * LEN}] = {{\n" + "\n".join(rows) + "\n};\n"
                   + f"static const float DF_WT_GAIN[{TABLES * FRAMES}][5] = {{\n"
                   + "\n".join("    {" + ", ".join(f"{g:.4f}f" for g in gain[i * 5:i * 5 + 5]) + "},"
                               for i in range(TABLES * FRAMES)) + "\n};\n")

if __name__ == "__main__":
    main()
